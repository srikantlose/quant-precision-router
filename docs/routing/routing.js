/* one lane laid out top-down: main column, side outcomes, loops on the left, skips left or right */
function lane(prefix, x0, y0, steps, o = {}) {
  const mx = x0 + (o.mx || 104), mw = o.mw || 180, sx = x0 + (o.sx || 246), sw = o.sw || 84, gap = o.gap || 8;
  const nodes = [], edges = [];
  let y = y0;
  steps.forEach((s, i) => {
    const t = s.t || "proc";
    const n = { id: `${prefix}${i}`, t, html: s.h, cls: s.cls, x: mx, w: s.w || (t === "dec" ? 172 : t === "term" ? mw - 10 : mw) };
    sizeNode(n);
    let side = null;
    if (s.side) { side = { id: `${prefix}s${i}`, t: s.side.t || "proc", html: s.side.h, cls: s.side.cls || "coral", w: s.side.w || sw }; sizeNode(side); side.x = sx - sw / 2 + side.w / 2; }
    const rh = Math.max(n.h, side ? side.h : 0);
    n.y = y + rh / 2; if (side) side.y = n.y;
    nodes.push(n); if (side) nodes.push(side);
    s._n = n; s._s = side; y += rh + gap;
  });
  steps.forEach((s, i) => {
    const n = s._n, nx = steps[i + 1];
    if (nx && !s.stop) edges.push({ a: n.id, as: "b", b: nx._n.id, bs: "t", label: s.t === "dec" ? (s.yes || "yes") : s.lab });
    if (s._s) {
      edges.push({ a: n.id, as: "r", b: s._s.id, bs: "l", label: s.side.lab !== undefined ? s.side.lab : s.t === "dec" ? "no" : undefined });
      if (s.side.join !== undefined) {
        const T = steps[s.side.join]._n;
        if (s.side.joinTop) { const yy = T.y - T.h / 2 - 5; edges.push({ a: s._s.id, as: "b", b: T.id, bs: "t", via: [[s._s.x, yy], [T.x, yy]] }); }
        else edges.push({ a: s._s.id, as: "b", b: T.id, bs: "r", via: [[s._s.x, T.y]] });
      }
    }
    if (s.loop) { const T = steps[s.loop.to]._n, gx = mx - mw / 2 - 9; edges.push({ a: n.id, as: "l", b: T.id, bs: "l", via: [[gx, n.y], [gx, T.y]], label: s.loop.lab || "yes" }); }
    if (s.skip) {
      const T = steps[s.skip.to]._n, left = s.skip.side === "l", gx = left ? mx - mw / 2 - 9 : mx + mw / 2 + 10;
      edges.push({ a: n.id, as: left ? "l" : "r", b: T.id, bs: left ? "l" : "r", via: [[gx, n.y], [gx, T.y]], label: s.skip.lab || "yes" });
    }
  });
  return { nodes, edges, bottom: y };
}
